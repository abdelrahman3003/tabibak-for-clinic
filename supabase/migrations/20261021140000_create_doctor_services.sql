-- Migration: create doctor_services table
create table if not exists public.doctor_services (
  id bigint generated by default as identity primary key,
  doctor_id uuid not null references public.doctors(doctor_id) on delete cascade,
  clinic_id bigint not null references public.clinic_data(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Indexes for performance
create index if not exists doctor_services_clinic_id_idx
  on public.doctor_services (clinic_id);

create index if not exists doctor_services_doctor_id_idx
  on public.doctor_services (doctor_id);

-- Enable Row Level Security
alter table public.doctor_services enable row level security;

-- Drop policies if already exist to allow clean reruns
drop policy if exists "Allow public select doctor_services" on public.doctor_services;
drop policy if exists "Doctors can insert their services" on public.doctor_services;
drop policy if exists "Doctors can update their services" on public.doctor_services;
drop policy if exists "Doctors can delete their services" on public.doctor_services;

-- Policies
create policy "Allow public select doctor_services"
  on public.doctor_services
  for select
  using (true);

create policy "Doctors can insert their services"
  on public.doctor_services
  for insert
  to authenticated
  with check (
    auth.uid() = doctor_id
    and exists (
      select 1 from public.clinic_data
      where clinic_data.id = clinic_id and clinic_data.doctor_id = auth.uid()
    )
  );

create policy "Doctors can update their services"
  on public.doctor_services
  for update
  to authenticated
  using (auth.uid() = doctor_id)
  with check (
    auth.uid() = doctor_id
    and exists (
      select 1 from public.clinic_data
      where clinic_data.id = clinic_id and clinic_data.doctor_id = auth.uid()
    )
  );

create policy "Doctors can delete their services"
  on public.doctor_services
  for delete
  to authenticated
  using (auth.uid() = doctor_id);

-- Grants
grant select, insert, update, delete on public.doctor_services to authenticated;
grant select on public.doctor_services to anon;

-- Optional trigger for updated_at
create or replace function public.set_doctor_services_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_set_doctor_services_updated_at on public.doctor_services;
create trigger trg_set_doctor_services_updated_at
before update on public.doctor_services
for each row execute function public.set_doctor_services_updated_at();
